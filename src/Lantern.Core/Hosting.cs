namespace Lantern.Core;

public enum HostKind { Listen, DedicatedIp, DedicatedP2P }
public sealed record GameMode(string Name, int Type, int Mode)
{
    public static readonly GameMode[] All = { new("地图自定义玩法", 3, 0), new("休闲", 0, 0), new("竞技", 0, 1), new("搭档", 0, 2), new("死亡竞赛", 1, 2), new("军备竞赛", 1, 0) };
}
public sealed record HostSettings
{
    public HostKind Kind { get; set; }
    public int ModeIndex { get; set; }
    public int Bots { get; set; } = 0;
    public int Difficulty { get; set; } = 2;
    public string QuotaMode { get; set; } = "normal";
    public int MaxPlayers { get; set; } = 10;
    public int Port { get; set; } = 27015;
    public int MaxRounds { get; set; } = 24;
    public int RoundMinutes { get; set; } = 3;
    public int FreezeSeconds { get; set; } = 5;
    public int StartMoney { get; set; } = 800;
    public bool FriendlyFire { get; set; }
    public bool AutoBalance { get; set; } = true;
    public bool Cheats { get; set; }
    public bool ApplyRules { get; set; }
    public string Name { get; set; } = "Lantern · 好友房间";
    public string Password { get; set; } = "";
    public string Token { get; set; } = "";
    public bool EnableConsole { get; set; } = true;
    public string ConsolePassword { get; set; } = "";
}
public sealed record LaunchPlan(string Rules, string Boot, string RulesName, string BootName, List<string> Arguments);

public static class Hosting
{
    public static IReadOnlyList<string> DeferredClientArguments(LaunchPlan plan)
    {
        if (plan.Arguments.Contains("-dedicated") || !plan.Arguments.Contains("-netconport") ||
            plan.Arguments.Count < 2 || plan.Arguments[^2] != "+exec" || plan.Arguments[^1] != plan.BootName)
            throw new ArgumentException("只有启用终端的客户端才能延后加载地图。");
        return plan.Arguments.Take(plan.Arguments.Count - 2).ToArray();
    }
    public static string SafeText(string value)
    {
        if (value.Length > 128 || value.Any(c => char.IsControl(c) || c is '"' or ';' or '\\')) throw new ArgumentException("名称／密码不能含换行、引号、分号、反斜杠，长度最多 128。");
        return value;
    }
    static void Range(int v, int min, int max, string name) { if (v < min || v > max) throw new ArgumentException($"{name}应为 {min}–{max}。"); }

    public static LaunchPlan Build(MapEntry map, HostSettings s, string session)
    {
        if (!Regex.IsMatch(session, @"^[a-z0-9_]{1,40}$")) throw new ArgumentException("Invalid session name");
        Range(s.ModeIndex, 0, GameMode.All.Length - 1, "模式"); Range(s.Bots, 0, 63, "人机数量"); Range(s.Difficulty, 0, 3, "人机难度");
        Range(s.MaxPlayers, 2, 64, "人数上限"); Range(s.Port, 1024, 65535, "端口"); Range(s.MaxRounds, 0, 1000, "回合上限");
        Range(s.RoundMinutes, 1, 60, "回合时间"); Range(s.FreezeSeconds, 0, 60, "冻结时间"); Range(s.StartMoney, 0, 60000, "初始金钱");
        if (s.QuotaMode == "fill" ? s.Bots > s.MaxPlayers : s.Bots >= s.MaxPlayers)
            throw new ArgumentException("固定人机数量须小于人数上限；补齐总人数可等于人数上限。");
        if (s.QuotaMode is not ("normal" or "fill" or "match")) throw new ArgumentException("Invalid bot quota mode");
        SafeText(s.Name); SafeText(s.Password);
        if (s.Token.Length > 0 && !Regex.IsMatch(s.Token, @"^[a-zA-Z0-9]{20,64}$")) throw new ArgumentException("GSLT 格式不正确。");
        if (s.Kind == HostKind.DedicatedP2P && s.Token.Length > 0) throw new ArgumentException("实验 P2P 使用匿名服务器身份，请清空 GSLT。");
        if (map.Official || s.Kind == HostKind.Listen)
        {
            if (!map.Local || !Regex.IsMatch(map.MapName, @"^[a-zA-Z0-9_\-]+$")) throw new ArgumentException("先在 Steam 完成订阅下载，再重新扫描本地地图。");
        }
        if (!map.Official) Workshop.ParseId(map.Id);
        if (!map.Local && !map.ValidatedRemote) throw new ArgumentException("请先验证该工坊条目属于 CS2 地图。");
        var rulesName = "lantern_" + session + "_rules.cfg";
        var bootName = "lantern_" + session + "_boot.cfg";
        var rules = new StringBuilder("// Generated by CS2 Lantern. Apply after map load.\n");
        rules.AppendLine($"hostname \"{s.Name}\"\nsv_password \"{s.Password}\"\nsv_lan 0");
        if (s.ApplyRules)
        {
            rules.AppendLine("bot_auto_vacate 0");
            rules.AppendLine($"bot_quota_mode {s.QuotaMode}\nbot_difficulty {s.Difficulty}\nbot_quota {s.Bots}");
            rules.AppendLine($"mp_maxrounds {s.MaxRounds}\nmp_roundtime {s.RoundMinutes}\nmp_roundtime_defuse {s.RoundMinutes}\nmp_roundtime_hostage {s.RoundMinutes}");
            rules.AppendLine($"mp_freezetime {s.FreezeSeconds}\nmp_startmoney {s.StartMoney}\nmp_friendlyfire {(s.FriendlyFire ? 1 : 0)}\nmp_autoteambalance {(s.AutoBalance ? 1 : 0)}\nmp_limitteams {(s.AutoBalance ? 2 : 0)}\nsv_cheats {(s.Cheats ? 1 : 0)}");
        }
        rules.AppendLine("echo LANTERN_RULES_APPLIED");
        var mode = GameMode.All[s.ModeIndex];
        var boot = new StringBuilder($"game_type {mode.Type}\ngame_mode {mode.Mode}\n");
        boot.AppendLine($"{(s.Kind == HostKind.Listen ? "lservercfgfile" : "servercfgfile")} {rulesName}");
        if (s.Kind == HostKind.Listen) boot.AppendLine("lobby_default_privacy_bits2 1");
        boot.AppendLine(map.Official ? "map " + map.MapName : s.Kind == HostKind.Listen ? $"map_workshop {map.Id} {map.MapName}" : $"host_workshop_map {map.Id}");
        var args = new List<string>();
        if (s.Kind != HostKind.Listen) args.Add("-dedicated");
        args.AddRange(new[] { "-console", "-port", s.Port.ToString(), "-maxplayers", s.MaxPlayers.ToString() });
        if (s.EnableConsole)
        {
            if (!Regex.IsMatch(s.ConsolePassword, @"^[a-zA-Z0-9]{16,64}$")) throw new ArgumentException("终端密码无效，请重新启动启动器。");
            args.AddRange(new[] { "-insecure", "-netconport", s.Kind == HostKind.Listen ? "2121" : "2122", "-netconpassword", s.ConsolePassword });
        }
        if (s.Kind == HostKind.DedicatedIp && s.Token.Length > 0) args.AddRange(new[] { "+sv_setsteamaccount", s.Token });
        // Workshop requests require an initialized Steam game server. The app waits
        // for login before executing the selected workshop map's boot config.
        if (s.Kind != HostKind.Listen && !map.Official)
        {
            if (!s.EnableConsole) throw new ArgumentException("独立工坊开服需要启用游戏终端，以等待 Steam 初始化并验证所选地图。");
            args.AddRange(new[] { "+map", "de_dust2" });
        }
        else args.AddRange(new[] { "+exec", bootName });
        return new(rules.ToString(), boot.ToString(), rulesName, bootName, args);
    }

    public static string WriteConfigs(string root, LaunchPlan plan)
    {
        var dir = Path.Combine(root, "game", "csgo", "cfg");
        if (!Directory.Exists(dir) || !File.Exists(Path.Combine(root, "game", "bin", "win64", "cs2.exe"))) throw new DirectoryNotFoundException("请先设置包含 game\\bin\\win64\\cs2.exe 的 CS2 安装根目录。");
        File.WriteAllText(Path.Combine(dir, plan.RulesName), plan.Rules, new UTF8Encoding(false));
        File.WriteAllText(Path.Combine(dir, plan.BootName), plan.Boot, new UTF8Encoding(false));
        return "exec " + plan.BootName;
    }

    public static string JoinCommand(string address, int port, string password)
    {
        address = address.Trim(); SafeText(password); Range(port, 1024, 65535, "端口");
        if (address.StartsWith("[A:") && !ValidServerIdentity(address)) throw new ArgumentException("服务器 Steam 身份为空或无效，请改用组网地址，或重新建立支持 P2P 的房间。");
        if (!Regex.IsMatch(address, @"^\[A:\d+:\d+:\d+\]$"))
        {
            if (!IPAddress.TryParse(address, out var ip)) throw new ArgumentException("请输入实际 IPv4 / IPv6 地址，或服务器 status 中的 [A:…] 身份。");
            address = ip.AddressFamily == System.Net.Sockets.AddressFamily.InterNetworkV6 ? $"[{ip}]:{port}" : $"{ip}:{port}";
        }
        return (password.Length > 0 ? $"password \"{password}\"; " : "") + "connect " + address;
    }
    public static string? ParseServerIdentity(string log)
    {
        foreach (var line in log.Split('\n'))
        {
            if (!Regex.IsMatch(line, @"\bsteamid\s*:", RegexOptions.IgnoreCase)) continue;
            var m = Regex.Match(line, @"\[A:\d+:\d+:\d+\]");
            if (m.Success && ValidServerIdentity(m.Value)) return m.Value;
        }
        return null;
    }
    static bool ValidServerIdentity(string value)
    {
        var match = Regex.Match(value, @"^\[A:\d+:(\d+):(\d+)\]$");
        return match.Success && ulong.TryParse(match.Groups[1].Value, out var account) && account > 0
            && ulong.TryParse(match.Groups[2].Value, out var instance) && instance > 0;
    }
}
